"""Bundle ``src/hindi_asr`` + ``kaggle/pipeline.py`` into one Kaggle script kernel.

    python kaggle/build_kernel.py --mode smoke   # -> kaggle/kernels/smoke/
    python kaggle/build_kernel.py --mode full    # -> kaggle/kernels/full/

Then push with the abhigyan1881 token (see README "Reproduce").
The generated script embeds the package as a base64 tarball, so the code that
ran on Kaggle is exactly the code in this commit.
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KAGGLE_USER = "abhigyan1881"
SLUGS = {"smoke": "hva-whisper-lora-smoke", "full": "hva-whisper-lora"}
# Packages the Kaggle image lacks or ships at an untested version; the image's torch/transformers are recorded at runtime.
PIP = ["peft==0.21.2", "jiwer==4.0.0"]

TEMPLATE = '''# Generated by kaggle/build_kernel.py - do not edit by hand.
import base64, io, os, subprocess, sys, tarfile
# The image's torchao 0.10 makes peft refuse to wrap layers; LoRA here does not need it.
subprocess.run([sys.executable, "-m", "pip", "uninstall", "-q", "-y", "torchao"], check=False)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", *{pip!r}], check=True)
os.makedirs("/kaggle/tmp/repo", exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode("{payload}"))).extractall("/kaggle/tmp/repo")
env = dict(os.environ, PYTHONPATH="/kaggle/tmp/repo/src", HF_HOME="/kaggle/tmp/hf", TOKENIZERS_PARALLELISM="false")
sys.exit(subprocess.run([sys.executable, "/kaggle/tmp/repo/kaggle/pipeline.py", "--mode", "{mode}", "--out", "/kaggle/working"], env=env).returncode)
'''


def payload() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for path in sorted((ROOT / "src" / "hindi_asr").glob("*.py")) + [ROOT / "kaggle" / "pipeline.py"]:
            tar.add(path, arcname=str(path.relative_to(ROOT)))
    return base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=sorted(SLUGS), required=True)
    args = ap.parse_args()
    slug = SLUGS[args.mode]
    out = ROOT / "kaggle" / "kernels" / args.mode
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{slug}.py").write_text(TEMPLATE.format(pip=PIP, payload=payload(), mode=args.mode))
    meta = {
        "id": f"{KAGGLE_USER}/{slug}",
        "title": slug,
        "code_file": f"{slug}.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_tpu": False,
        "enable_internet": True,
        "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [],
        "kernel_sources": [],
        "competition_sources": [],
        "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(out)


if __name__ == "__main__":
    main()
